// service/windows.ts — Windows：开机登录后自动运行、不弹窗口、崩溃自动重启，都不需要管理员（设计 §16）
//
// - 自启：写进当前用户的 Run 键（HKCU\Software\Microsoft\Windows\CurrentVersion\Run）；
// - 不弹黑窗口：引擎和 node 都是控制台程序，直接运行会弹窗。用 wscript 跑一个隐藏窗口的小脚本（.vbs，style 0）启动；
// - 崩溃重启：小脚本启动的是 `dsh-model service supervise <spec>`，它用 windowsHide 拉起真正的程序，退出了就隔几秒再拉；
// - 停止：supervise 把自己的 pid 写进 <label>.pid，taskkill /T /F 连同子进程一起结束。
// wscript 启动完就退出，所以 supervise 不挂在调用者的进程树下（taskkill /T 调用者时不会被连带杀掉）。

import { spawn } from 'node:child_process'
import { readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { DshModelError } from '../errors.js'
import { L } from '../i18n.js'
import { run } from '../util/exec.js'
import { atomicWrite, exists } from '../util/fs.js'
import { PKG_ROOT } from '../util/pkg.js'
import type { ServiceManager, ServiceSpec, ServiceStatus } from './index.js'

export const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'

/** supervise 读的说明书 */
export interface SuperviseSpec {
  label: string
  program: string[]
  cwd: string
  env: Record<string, string>
  stdout: string
  pidFile: string
}

const paths = (spec: ServiceSpec) => {
  const base = spec.file.replace(/\.json$/i, '')
  return { json: spec.file, vbs: `${base}.vbs`, pid: `${base}.pid` }
}

/** VBScript 字符串里的双引号要写两遍 */
const vbq = (s: string) => `"${s.replace(/"/g, '""')}"`

/** 隐藏窗口启动 supervise 的小脚本。存成 UTF-16LE（带 BOM），路径里有中文也不乱码 */
export function renderVbs(spec: ServiceSpec, node = process.execPath, electron = Boolean(process.versions.electron)): string {
  const cmd = [node, join(PKG_ROOT, 'bin', 'dsh-model.js'), 'service', 'supervise', spec.file].map((a) => `""${a.replace(/"/g, '""""')}""`).join(' ')
  return [
    "' Generated by dsh-model. 由 dsh-model 生成：隐藏窗口启动后台服务，卸载请执行 dsh-model uninstall",
    'Set sh = CreateObject("WScript.Shell")',
    // 从 dsh 桌面版一键安装时 node 就是 DeepSeek Harness.exe：让它当 Node 跑
    ...(electron ? ['sh.Environment("Process")("ELECTRON_RUN_AS_NODE") = "1"'] : []),
    `sh.Run "${cmd}", 0, False`,
    '',
  ].join('\r\n')
}

export function renderSupervise(spec: ServiceSpec): SuperviseSpec {
  return {
    label: spec.label,
    program: spec.program,
    cwd: spec.workingDirectory,
    env: { ...spec.env, ...(process.versions.electron ? { ELECTRON_RUN_AS_NODE: '1' } : {}) },
    stdout: spec.stdoutPath,
    pidFile: paths(spec).pid,
  }
}

function alive(pid: number): boolean {
  try {
    process.kill(pid, 0)
    return true
  } catch {
    return false
  }
}

async function readPid(file: string): Promise<number | undefined> {
  const n = Number((await readFile(file, 'utf8').catch(() => '')).trim())
  return Number.isInteger(n) && n > 0 ? n : undefined
}

export function windowsService(spec: ServiceSpec): ServiceManager {
  const p = paths(spec)
  const runValue = `wscript.exe //B //Nologo "${p.vbs}"`

  const running = async () => {
    const pid = await readPid(p.pid)
    return pid && alive(pid) ? pid : undefined
  }
  const start = async () => {
    if (await running()) return
    const child = spawn('wscript.exe', ['//B', '//Nologo', p.vbs], { detached: true, stdio: 'ignore', windowsHide: true })
    child.unref()
    const deadline = Date.now() + 10_000
    while (Date.now() < deadline && !(await running())) await new Promise((r) => setTimeout(r, 200))
    if (!(await running())) throw new DshModelError('service_failed', L(`后台服务 ${spec.label} 没有启动（看日志：${spec.stdoutPath}）`, `Background service ${spec.label} did not start (log: ${spec.stdoutPath})`), L('可能被杀毒软件拦截：把 dsh-model 的目录加入信任后执行 dsh-model repair', 'An antivirus may have blocked it: trust the dsh-model folder, then run dsh-model repair'))
  }
  const stop = async () => {
    const pid = await readPid(p.pid)
    if (pid && alive(pid)) await run('taskkill', ['/PID', String(pid), '/T', '/F'])
    await rm(p.pid, { force: true })
  }

  return {
    kind: 'windows',
    spec,
    render: () => `${JSON.stringify(renderSupervise(spec), null, 2)}\n\n${renderVbs(spec)}`,
    async install() {
      await atomicWrite(p.json, JSON.stringify(renderSupervise(spec), null, 2), { mode: 0o600 })
      await writeFile(p.vbs, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(renderVbs(spec), 'utf16le')]))
      const r = await run('reg', ['add', RUN_KEY, '/v', spec.label, '/t', 'REG_SZ', '/d', runValue, '/f'])
      if (r.code !== 0) throw new DshModelError('service_failed', L(`写开机自启失败：${r.stderr.trim()}`, `Failed to register autostart: ${r.stderr.trim()}`))
      await stop()
      await start()
    },
    start,
    stop,
    async restart() {
      await stop()
      await start()
    },
    async status(): Promise<ServiceStatus> {
      const installed = await exists(p.json)
      const pid = await running()
      return { installed, running: Boolean(pid), ...(pid ? { pid } : {}), detail: pid ? 'running' : installed ? 'stopped' : 'not installed' }
    },
    async uninstall() {
      await stop()
      await run('reg', ['delete', RUN_KEY, '/v', spec.label, '/f'])
      await rm(p.json, { force: true })
      await rm(p.vbs, { force: true })
    },
  }
}

/**
 * `dsh-model service supervise <spec.json>`：由隐藏窗口脚本启动，常驻。
 * 拉起程序（不弹窗，输出追加到日志）；程序退出就隔几秒重拉（太频繁就拉长间隔）。被 taskkill /T 时连同子进程一起结束。
 */
export async function supervise(specFile: string): Promise<number> {
  const s = JSON.parse(await readFile(specFile, 'utf8')) as SuperviseSpec
  const { closeSync, openSync } = await import('node:fs')
  await atomicWrite(s.pidFile, String(process.pid), { mode: 0o600 })
  let backoff = 2_000
  for (;;) {
    const startedAt = Date.now()
    const out = openSync(s.stdout, 'a')
    const code = await new Promise<number>((resolve) => {
      const child = spawn(s.program[0]!, s.program.slice(1), { cwd: s.cwd, env: { ...process.env, ...s.env }, stdio: ['ignore', out, out], windowsHide: true })
      child.on('error', () => resolve(-1))
      child.on('exit', (c) => resolve(c ?? -1))
    })
    closeSync(out)
    await writeFile(s.stdout, `[${new Date().toISOString()}] dsh-model supervise: ${s.label} exited (${code}); restarting\n`, { flag: 'a' }).catch(() => {})
    // 跑了一分钟以上才退出的算正常崩溃，间隔恢复到 2 秒；一启动就退出的逐步拉长到 60 秒，免得空转
    backoff = Date.now() - startedAt > 60_000 ? 2_000 : Math.min(backoff * 2, 60_000)
    await new Promise((r) => setTimeout(r, backoff))
    if (!(await exists(dirname(s.pidFile)))) return 0
  }
}
